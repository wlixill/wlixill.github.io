// Build the article index, static pages and discovery files for GitHub Pages.
// Usage: node dev/build-posts.mjs (Node 22+, no npm dependencies).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontMatter, renderMarkdown } from '../assets/markdown.js';
import { icon } from '../assets/icons.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceDir = path.join(root, 'content/posts');
const postsDir = path.join(root, 'posts');
// Canonical public URL, not the local preview URL. Keep the trailing slash.
const siteUrl = new URL('https://wlixill.github.io/');
const generatedHtml = '<!-- Generated by dev/build-posts.mjs; do not edit. -->';
const generatedXml = '<!-- Generated by dev/build-posts.mjs; do not edit. -->';
const generatedText = '# Generated by dev/build-posts.mjs; do not edit.';

const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (c) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[c]));
const postUrl = (slug) => new URL(`posts/${slug}/`, siteUrl).href;
const postPath = (slug) => new URL(`posts/${slug}/`, siteUrl).pathname;
const archiveUrl = new URL('posts/', siteUrl).href;
const archivePath = new URL('posts/', siteUrl).pathname;
const imageUrl = new URL('assets/bg/stormlight-fields-poster.jpg', siteUrl).href;
const formatDate = (date) => date.replace(/-/g, '.');

function readingMinutes(md) {
  const cjk = (md.match(/[\u4e00-\u9fff]/g) || []).length;
  const words = (md.match(/[A-Za-z0-9]+/g) || []).length;
  return Math.max(1, Math.round(cjk / 350 + words / 220));
}

// Index what the reader sees, not front matter or the copy-button label. Strip
// HTML before decoding entities so code such as "a < b" stays searchable.
function searchText(html) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" };
  return html
    .replace(/<div class="code-block-head">[\s\S]*?<\/div>/g, ' ')
    .replace(/<img\b[^>]*\balt="([^"]*)"[^>]*\/?\s*>/g, ' $1 ')
    .replace(/<\/?(?:div|h[1-6]|p|li|pre|td|th|tr|blockquote|hr|br|ul|ol|table|thead|tbody)\b[^>]*>/g, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/&(amp|lt|gt|quot|#39);/g, (_, entity) => entities[entity])
    .replace(/\s+/g, ' ')
    .trim();
}

function replaceSection(html, name, content) {
  const start = `<!-- ${name}_START -->`;
  const end = `<!-- ${name}_END -->`;
  const from = html.indexOf(start);
  const to = html.indexOf(end, from + start.length);
  if (from === -1 || to === -1 || html.indexOf(start, from + start.length) !== -1 || html.indexOf(end, to + end.length) !== -1) {
    throw new Error(`index.html must contain exactly one ordered ${name} marker pair`);
  }
  return html.slice(0, from + start.length) + '\n' + content + '\n  ' + html.slice(to);
}

function pageMetadata({ title, description, url, base, type = 'website', date }) {
  const tags = [
    `  <base href="${escapeHtml(base)}" />`,
    `  <title>${escapeHtml(title)}</title>`,
    `  <meta name="description" content="${escapeHtml(description)}" />`,
    `  <link rel="canonical" href="${escapeHtml(url)}" />`,
    `  <meta property="og:type" content="${type}" />`,
    '  <meta property="og:site_name" content="wlixill · 笔记与工具" />',
    '  <meta property="og:locale" content="zh_CN" />',
    `  <meta property="og:title" content="${escapeHtml(title)}" />`,
    `  <meta property="og:description" content="${escapeHtml(description)}" />`,
    `  <meta property="og:url" content="${escapeHtml(url)}" />`,
    `  <meta property="og:image" content="${escapeHtml(imageUrl)}" />`,
    '  <meta name="twitter:card" content="summary_large_image" />',
    `  <meta name="twitter:title" content="${escapeHtml(title)}" />`,
    `  <meta name="twitter:description" content="${escapeHtml(description)}" />`,
    `  <meta name="twitter:image" content="${escapeHtml(imageUrl)}" />`,
  ];
  if (date) tags.push(`  <meta property="article:published_time" content="${escapeHtml(date)}" />`);
  return tags.join('\n');
}

function makePage(template, metadata, content, bodyAttribute, pagePath) {
  let html = replaceSection(template, 'PAGE_META', pageMetadata(metadata));
  html = replaceSection(html, 'STATIC_VIEW', content);
  if (!/<body(?:\s[^>]*)?>/.test(html)) throw new Error('index.html body element not found');
  html = html.replace(/<body(\s[^>]*)?>/, (_, attrs = '') => `<body${attrs} ${bodyAttribute}>`);
  // A <base> makes hash-only links resolve at the site root. Keep the skip
  // link on this document instead; the same applies to article anchor links.
  const skip = /(<a\b[^>]*\bclass="[^"]*\bskip-link\b[^"]*"[^>]*\bhref=")#view(")/;
  if (!skip.test(html)) throw new Error('index.html skip link not found');
  html = html.replace(skip, (_, before, after) => `${before}${escapeHtml(pagePath)}#view${after}`);
  return html.replace('<!doctype html>', `<!doctype html>\n${generatedHtml}`);
}

const tagLink = (tag) => `<a class="tag" href="#/posts/${encodeURIComponent(tag)}">${escapeHtml(tag)}</a>`;

function articleMarkup(post, older, newer) {
  // Preserve same-document anchors despite <base>; upgrade legacy article
  // links inside Markdown to real paths as well.
  const body = post.html
    .replace(/href="#\/post\/([a-z0-9]+(?:-[a-z0-9]+)*)\/?"/g, (_, slug) => `href="${postPath(slug)}"`)
    .replace(/href="#(?!\/)([^"]*)"/g, (_, anchor) => `href="${postPath(post.slug)}#${anchor}"`);
  return `        <div class="post-wrap">
          <a class="backlink" href="${archivePath}">${icon('arrowLeft')}全部文章</a>
          <article class="post">
            <header class="post-head">
              <h1>${escapeHtml(post.title)}</h1>
              <div class="post-meta">
                <time datetime="${escapeHtml(post.date)}">${formatDate(post.date)}</time>
                <span class="dot"></span>
                <span>${post.minutes} 分钟</span>
                <span class="dot"></span>
                <span class="post-meta-tags">${post.tags.map(tagLink).join('')}</span>
              </div>
            </header>
            <div class="post-body">${body}</div>
            <footer class="post-foot">
              <div class="post-nav">
${older ? `                <a class="post-nav-item" href="${postPath(older.slug)}"><span>上一篇</span><strong>${escapeHtml(older.title)}</strong></a>\n` : ''}${newer ? `                <a class="post-nav-item next" href="${postPath(newer.slug)}"><span>下一篇</span><strong>${escapeHtml(newer.title)}</strong></a>\n` : ''}              </div>
            </footer>
          </article>
        </div>`;
}

function archiveMarkup(posts) {
  return `        <header class="page-head">
          <span class="page-kicker">${posts.length} 篇</span>
          <h1>全部文章</h1>
          <p>按时间倒序。每一篇都来自一次真实的调试。</p>
        </header>
        <div class="post-rows">
          ${posts.map((post) => `<a class="post-row" href="${postPath(post.slug)}">
            <time class="post-row-date" datetime="${escapeHtml(post.date)}">${formatDate(post.date)}</time>
            <div class="post-row-main"><h3>${escapeHtml(post.title)}</h3><p>${escapeHtml(post.summary)}</p></div>
            <span class="post-row-arrow">${icon('arrowRight')}</span>
          </a>`).join('\n          ')}
        </div>`;
}

const files = fs.readdirSync(sourceDir).filter((file) => file.endsWith('.md')).sort();
const posts = files.map((file) => {
  const slug = file.slice(0, -3);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
    throw new Error(`${file}: slug must use lowercase ASCII letters, numbers and single hyphens`);
  }
  const { data, body } = parseFrontMatter(fs.readFileSync(path.join(sourceDir, file), 'utf8'));
  if (!data.title || !data.summary || !/^\d{4}-\d{2}-\d{2}$/.test(data.date || '')) {
    throw new Error(`${file}: front matter must include title, summary and a YYYY-MM-DD date`);
  }
  const { html } = renderMarkdown(body);
  return {
    slug,
    title: data.title,
    date: data.date,
    summary: data.summary,
    tags: Array.isArray(data.tags) ? data.tags : data.tags ? [data.tags] : [],
    featured: data.featured === 'true' || data.featured === true,
    minutes: readingMinutes(body),
    searchText: searchText(html),
    html,
  };
}).sort((a, b) => a.date === b.date ? (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0) : a.date > b.date ? -1 : 1);

const template = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const index = posts.map(({ html, ...post }) => post);
const outputs = [{ file: path.join(root, 'content/posts.json'), text: JSON.stringify(index, null, 2) + '\n' }];
outputs.push({
  file: path.join(postsDir, 'index.html'), marker: generatedHtml,
  text: makePage(template, {
    title: '全部文章 · wlixill',
    description: 'wlixill 的机器人感知、调试复盘与工程方法文章，按时间倒序浏览。',
    url: archiveUrl, base: '../',
  }, archiveMarkup(posts), 'data-static-archive', archivePath),
});
posts.forEach((post, i) => {
  outputs.push({
    file: path.join(postsDir, post.slug, 'index.html'), marker: generatedHtml,
    text: makePage(template, {
      title: `${post.title} · wlixill`, description: post.summary, url: postUrl(post.slug),
      base: '../../', type: 'article', date: post.date,
    }, articleMarkup(post, posts[i + 1], posts[i - 1]), `data-static-post="${post.slug}"`, postPath(post.slug)),
  });
});
const sitemapUrls = [siteUrl.href, archiveUrl, ...posts.map((post) => postUrl(post.slug))];
outputs.push({
  file: path.join(root, 'sitemap.xml'), marker: generatedXml,
  text: `<?xml version="1.0" encoding="UTF-8"?>\n${generatedXml}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemapUrls.map((url) => `  <url><loc>${escapeHtml(url)}</loc></url>`).join('\n')}\n</urlset>\n`,
});
outputs.push({
  file: path.join(root, 'robots.txt'), marker: generatedText,
  text: `${generatedText}\nUser-agent: *\nAllow: /\nSitemap: ${new URL('sitemap.xml', siteUrl).href}\n`,
});

// Refuse to overwrite hand-authored pages/discovery files. Never delete stale
// output: review and remove an old generated directory explicitly if a slug is
// renamed or an article is removed.
for (const { file, marker } of outputs) {
  if (fs.existsSync(file) && marker && !fs.readFileSync(file, 'utf8').includes(marker)) {
    throw new Error(`Refusing to overwrite non-generated file: ${path.relative(root, file)}`);
  }
}
for (const { file, text } of outputs) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text, 'utf8');
}
console.log(`Built ${posts.length} articles, the archive, posts.json, sitemap.xml and robots.txt.`);
posts.forEach((post) => console.log(`  ${post.date}  ${post.title}  (${post.minutes} min)`));
